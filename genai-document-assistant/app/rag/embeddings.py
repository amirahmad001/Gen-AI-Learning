'''
Accept document chunks generated by the chunker.
Load the configured embedding model.
Convert text chunks into numerical vector representations.
Generate embeddings for document content.
Return embeddings ready for storage in the vector database.
'''

from langchain_ollama import OllamaEmbeddings
from langchain_core.documents import Document

model = OllamaEmbeddings(model="all-minilm:latest")


def embed_documents(documents: list[Document]):

    if not documents:
        return []

    # Extract text from Document objects
    texts = [doc.page_content for doc in documents]

    # Generate embeddings
    embedded_vectors = model.embed_documents(texts)

    return embedded_vectors